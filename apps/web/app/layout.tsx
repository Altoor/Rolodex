import "@repo/ui/styles.css";
import "./globals.css";
import type { Metadata } from "next";
import { GeistSans } from "geist/font/sans";
import { normalizeApiOrigin } from "@repo/ui/lib/apiOrigin";
import App from "./App";

export const metadata: Metadata = {
  title: "Create Turborepo",
  description: "Generated by create turbo",
};

// Read API_PUBLIC_ORIGIN per request so the published image does not bake a
// deployment-specific URL into the static HTML.
export const dynamic = "force-dynamic";

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const apiOrigin = normalizeApiOrigin(process.env.API_PUBLIC_ORIGIN) ?? "";

  return (
    <html lang="en">
      <body
        className={`${GeistSans.className} min-h-dvh bg-background text-foreground antialiased`}
      >
        <App apiOrigin={apiOrigin}>{children}</App>
      </body>
    </html>
  );
}
